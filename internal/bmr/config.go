package bmr

import (
	"fmt"
	"path/filepath"
	"strings"
	"text/template"
)

// RecoveryRoot is where ReaR mounts the recreated root filesystem before it
// runs EXTERNAL_RESTORE. Everything the recovery agent writes goes under it.
const RecoveryRoot = "/mnt/local"

// Default locations for the files the recovery media needs. They are
// overridable so a build can be exercised from a temp dir in tests and so
// distributions that lay binaries out differently can adapt.
const (
	DefaultOutputDir   = "/var/lib/hitstor/bmr"
	DefaultAgentBinary = "/usr/bin/hitstor-agent"
	DefaultHookScript  = "/usr/share/hitstor/bmr/hitstor-recover.sh"
	DefaultReaRConfig  = "/etc/rear/local.conf"
)

// ConfigOptions describes the recovery media to build for one host.
type ConfigOptions struct {
	// OutputDir is where ReaR writes the finished ISO. Absolute.
	OutputDir string
	// AgentBinary is the hitstor-agent to embed in the rescue image. Absolute.
	AgentBinary string
	// HookScript is the EXTERNAL_RESTORE entry point, embedded alongside the
	// agent. Absolute.
	HookScript string

	// ServerAddr prefills the prompt in the recovery hook. It is a
	// convenience, not a credential, and the operator can override it at
	// recovery time.
	ServerAddr string

	// AgentName is the registered agent this media recovers. Baked into the
	// hook so the rescue system asks the server for the right host's data
	// even when its own hostname comes back wrong or blank. Not a credential.
	AgentName string

	// MigrationMode relaxes ReaR's insistence that the recovery hardware match
	// the original. Needed for P2V and for dissimilar replacement hardware.
	MigrationMode bool

	// ExtraCopyAsIs adds host-specific files to the rescue image — a corporate
	// CA bundle, say, without which the agent cannot verify the server.
	ExtraCopyAsIs []string
}

// withDefaults fills in unset paths.
func (o ConfigOptions) withDefaults() ConfigOptions {
	if o.OutputDir == "" {
		o.OutputDir = DefaultOutputDir
	}
	if o.AgentBinary == "" {
		o.AgentBinary = DefaultAgentBinary
	}
	if o.HookScript == "" {
		o.HookScript = DefaultHookScript
	}
	return o
}

// validate rejects options that would produce media ReaR cannot build or that
// would fail only once an operator is standing in front of a dead machine.
func (o ConfigOptions) validate() error {
	for _, f := range []struct {
		name, value string
	}{
		{"output directory", o.OutputDir},
		{"agent binary", o.AgentBinary},
		{"hook script", o.HookScript},
	} {
		if f.value == "" {
			return fmt.Errorf("bmr: %s is required", f.name)
		}
		if !filepath.IsAbs(f.value) {
			return fmt.Errorf("bmr: %s must be an absolute path, got %q", f.name, f.value)
		}
	}
	return nil
}

// shellQuote renders s as a single-quoted POSIX shell word.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

var configTemplate = template.Must(template.New("local.conf").Funcs(template.FuncMap{
	"quote": shellQuote,
}).Parse(`# Generated by HitStor — bare-metal recovery media configuration.
#
# Do not edit by hand: 'hitstor bmr generate-config' overwrites this file on
# every media build. Host-specific additions belong in /etc/rear/site.conf,
# which ReaR reads alongside this file.
#
# ReaR recreates the disk layout and reinstalls the bootloader; HitStor
# restores the data. ReaR itself is told to back up nothing, and to hand the
# recovery run to HitStor through EXTERNAL_RESTORE.

OUTPUT=ISO
OUTPUT_URL=file://{{ .OutputDir }}

BACKUP=EXTERNAL
EXTERNAL_BACKUP=()
EXTERNAL_RESTORE=({{ quote .HookScript }})
EXTERNAL_CHECK=()

# The rescue system must reach the HitStor server on its own: the recovery
# agent calls home, and nobody should have to configure networking by hand
# during an outage.
USE_DHCLIENT=yes

# Everything the recovery run needs, inside the image.
COPY_AS_IS+=( {{ quote .AgentBinary }} {{ quote .HookScript }}{{ range .ExtraCopyAsIs }} {{ quote . }}{{ end }} )
PROGS+=( {{ quote .AgentBinary }} )
{{ if .MigrationMode }}
# Recovery hardware may differ from the original (P2V, replacement machine).
# ReaR remaps devices and regenerates the initramfs with the drivers the new
# hardware needs.
MIGRATION_MODE=true
{{ end }}
# HitStor holds no repository credentials on this media by design; they are
# prompted for at recovery time.
`))

// RenderConfig produces the /etc/rear/local.conf that points ReaR at HitStor.
func RenderConfig(opts ConfigOptions) (string, error) {
	opts = opts.withDefaults()
	if err := opts.validate(); err != nil {
		return "", err
	}

	var sb strings.Builder
	if err := configTemplate.Execute(&sb, opts); err != nil {
		return "", fmt.Errorf("bmr: render ReaR config: %w", err)
	}
	return sb.String(), nil
}

var hookTemplate = template.Must(template.New("recover.sh").Funcs(template.FuncMap{
	"quote": shellQuote,
}).Parse(`#!/bin/bash
# Generated by HitStor — ReaR EXTERNAL_RESTORE hook.
#
# ReaR runs this after it has recreated the disk layout and mounted the new
# root at {{ .RecoveryRoot }}. It launches the HitStor agent in recovery mode,
# which announces itself to the server and then receives the restore.
#
# ReaR installs the bootloader only if this script exits 0, so a failed restore
# must surface as a non-zero exit rather than a confidently broken machine.

set -u
set -o pipefail

AGENT={{ quote .AgentBinary }}
TARGET={{ quote .RecoveryRoot }}
SERVER={{ quote .ServerAddr }}
AGENT_NAME={{ quote .AgentName }}

echo
echo "=== HitStor bare-metal recovery ==="
echo
echo "The disk layout has been recreated and mounted at ${TARGET}."
echo "Enter the recovery details issued from the HitStor dashboard"
echo "(Disaster Recovery -> Bare Metal -> Prepare bare-metal recovery)."
echo

if [ -n "${SERVER}" ]; then
  read -r -p "Server address [${SERVER}]: " server_input
  SERVER="${server_input:-${SERVER}}"
else
  read -r -p "Server address (host:port): " SERVER
fi

if [ -n "${AGENT_NAME}" ]; then
  read -r -p "Agent to recover [${AGENT_NAME}]: " agent_input
  AGENT_NAME="${agent_input:-${AGENT_NAME}}"
else
  read -r -p "Agent to recover: " AGENT_NAME
fi

# The recovery token is single-use and short-lived, and is deliberately not
# stored on this media.
read -r -p "Recovery token: " RECOVERY_TOKEN

if [ -z "${SERVER}" ] || [ -z "${RECOVERY_TOKEN}" ] || [ -z "${AGENT_NAME}" ]; then
  echo "hitstor: server address, agent name and recovery token are all required" >&2
  exit 1
fi

if [ ! -x "${AGENT}" ]; then
  echo "hitstor: recovery agent missing from rescue media at ${AGENT}" >&2
  exit 1
fi

"${AGENT}" recover \
  --server "${SERVER}" \
  --agent "${AGENT_NAME}" \
  --token "${RECOVERY_TOKEN}" \
  --target "${TARGET}"
rc=$?

if [ "${rc}" -ne 0 ]; then
  echo "hitstor: recovery failed (exit ${rc}); not installing a bootloader" >&2
  exit "${rc}"
fi

echo "hitstor: data restored into ${TARGET}"
exit 0
`))

// RenderHookScript produces the EXTERNAL_RESTORE script embedded in the media.
func RenderHookScript(opts ConfigOptions) (string, error) {
	opts = opts.withDefaults()
	if err := opts.validate(); err != nil {
		return "", err
	}

	data := struct {
		ConfigOptions
		RecoveryRoot string
	}{ConfigOptions: opts, RecoveryRoot: RecoveryRoot}

	var sb strings.Builder
	if err := hookTemplate.Execute(&sb, data); err != nil {
		return "", fmt.Errorf("bmr: render recovery hook: %w", err)
	}
	return sb.String(), nil
}
